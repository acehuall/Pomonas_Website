import { execFileSync } from 'node:child_process';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = fileURLToPath(new URL('..', import.meta.url));
const destination = path.join(root, 'src/assets/images');
const cache = path.join(root, '.cache/image-sources');
// Originals remain reproducible from Git after Photos/ is removed.
const originalCommit = '472bffebe5d2aaa8391a3d7ebe48cfcbfe9f536d';
const sourceDirectory = process.argv[2] && path.resolve(process.argv[2]);
const sources = [
  { name: 'frog', original: 'Frog Photo.jpg', edge: 1600 },
  { name: 'jewellery', original: 'Jewelry.jpg', edge: 1000 },
  { name: 'mexico', original: 'Mexigo Photo.jpg', edge: 1600 },
  { name: 'monstera-print', original: 'Monstera Plant Print.png', edge: 1000 },
  { name: 'net-bag', original: 'Net Bag.jpg', edge: 1000 },
  { name: 'orange-vase', original: 'Orange vase.jpg', edge: 1000 },
  { name: 'cap', original: 'Pomonas hat.png', edge: 1000 },
  { name: 'tea-towel', original: 'Tea Towel Image (600x600).png', edge: 1000 },
  // Photo credit: Unsplash. These are the two images used by the original Home page.
  { name: 'hero-foliage', url: 'https://images.unsplash.com/photo-1528183429752-a97d0bf99b5a?q=80&w=1920&auto=format&fit=crop', edge: 1600 },
  { name: 'rustic-table', url: 'https://images.unsplash.com/photo-1490914327627-9fe8d52f4d90?q=80&w=1200&auto=format&fit=crop', edge: 1600 },
];

await mkdir(destination, { recursive: true });
await mkdir(cache, { recursive: true });
const report = [];
const imports = [];
const exports = [];
for (const source of sources) {
  let input;
  if (source.url) {
    const cachedPath = path.join(cache, source.name);
    try {
      input = await readFile(cachedPath);
    } catch (error) {
      if (error.code !== 'ENOENT') throw error;
      const response = await fetch(source.url, { signal: AbortSignal.timeout(30000) });
      if (!response.ok) throw new Error(`Download failed: ${source.url} (${response.status})`);
      input = Buffer.from(await response.arrayBuffer());
      await writeFile(cachedPath, input);
    }
  } else if (sourceDirectory) {
    input = await readFile(path.join(sourceDirectory, source.original));
  } else {
    try {
      input = execFileSync('git', ['show', `${originalCommit}:Photos/${source.original}`], {
        cwd: root, maxBuffer: 32 * 1024 * 1024,
      });
    } catch {
      throw new Error('Original photos unavailable. Fetch full Git history or pass a directory containing the original Photos filenames.');
    }
  }
  let output;
  let quality = 80;
  let edge = source.edge;
  while (true) {
    output = await sharp(input).rotate()
      .resize({ width: edge, height: edge, fit: 'inside', withoutEnlargement: true })
      .webp({ quality, effort: 6 }).toBuffer({ resolveWithObject: true });
    if (output.data.length < 250000) break;
    if (quality > 70) quality -= 5;
    else edge = Math.floor(edge * 0.9);
  }
  await writeFile(path.join(destination, `${source.name}.webp`), output.data);
  const { width, height } = output.info;
  const key = source.name.replace(/-([a-z])/g, (_, letter) => letter.toUpperCase());
  imports.push(`import ${key}Src from './${source.name}.webp';`);
  exports.push(`export const ${key} = { src: ${key}Src, width: ${width}, height: ${height} } as const;`);
  report.push({ file: `${source.name}.webp`, before: input.length, after: output.data.length, width, height, quality });
}
await writeFile(path.join(destination, 'index.ts'), [
  '// Generated by scripts/optimise-images.mjs. Do not edit dimensions by hand.',
  '// Home hero and story photos: Unsplash; source URLs are recorded in the script.',
  ...imports, '', ...exports, '',
].join('\n'));
const before = report.reduce((total, item) => total + item.before, 0);
const after = report.reduce((total, item) => total + item.after, 0);
await writeFile(path.join(root, 'scripts/image-report.json'), JSON.stringify({ before, after, images: report }, null, 2) + '\n');
console.table(report);
console.log(`Total: ${before.toLocaleString()} → ${after.toLocaleString()} bytes (${(100 * (1 - after / before)).toFixed(1)}% smaller).`);
